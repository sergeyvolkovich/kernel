// ==== Контракт планировщика (трейт БЕЗ реализации) ====
//
// Крейт не содержит кода планирования: порядок исполнения задач выбирает
// бекенд ВНЕ крейта (см. также комментарий к `TaskPriority` в
// `task::types`). Здесь определён только контракт [`SchedulerInterface`],
// который этот бекенд обязан реализовать, и правила его стыковки с
// подсистемой задач ([`crate::task::TcbManager`]) и подсистемой памяти
// ([`crate::mem::MemoryManager`]).
//
// Зачем подсистеме памяти контракт с планировщиком. Meltdown/Spectre
// (обсуждение и словарь регионов — в `hal::traits::kmap`) закрываются
// изоляцией таблиц страниц (KPTI): полное ядро живёт только в ядровых
// таблицах, в пользовательских — трамплин входа и user-shared страницы.
// Переключение «пользовательская таблица <-> ядровая» происходит на границе
// режимов и на КАЖДОМ переключении контекста, то есть исполняется
// планировщиком. Поэтому контракт фиксирует два требования:
//   1. планировщик обязан активировать адресные пространства только через
//      архитектурный бекенд MMAP/KMAP — прямые записи в регистры таблиц
//      страниц (CR3/TTBR-аналоги) в обход контракта запрещены: именно там
//      невидимо для крейта живёт физика и семантика изоляции;
//   2. планировщик декларирует политику изоляции ([`Self::isolation_policy`]);
//      она обязана совпадать с политикой KMap, по которой создавались фасады
//      задач (`MemoryManager::kmap().policy()`). Дефолт — консервативная
//      KPTI-изоляция: крейт, как и всюду, не доверяет железу до
//      доказательства платформой.
//
// Направления вызовов (кто кого дёргает):
//   TcbManager -> планировщик: `enqueue` / `deschedule` /
//       `on_priority_change` — уведомления о переходах автомата состояний
//       (ставятся хуками `TcbManager`, см. `install_scheduler`);
//   планировщик -> арх-бекенд: `switch_context` — диспетчеризация;
//       после переключения платформенный glue переводит задачу в `Running`
//       обычным переходом автомата (`TcbManager::set_state`).
// Обратных трейтов не вводится: планировщику достаточно ссылки на
// `TcbManager`, чтобы выставлять состояния.

use thiserror::Error;

use crate::hal::traits::kmap::IsolationPolicy;
use crate::task::types::{TaskId, TaskPriority, ThreadId};

/// Логический номер CPU: `0..cpu_count` системы.
///
/// Отдельного нового типа сознательно нет: нумерация и топология CPU —
/// знание платформы; крейт умеет только сравнивать и хранить номера.
pub type CpuId = usize;

/// Идентификатор очереди блокировки в бекенде планировщика.
///
/// Очереди блокировки ЖИВУТ В ПЛАНИРОВЩИКЕ (отдельный крейт — его код
/// здесь не пишется, только контракт): ядро просит бекенд создать/уничтожить
/// очередь и парковать/будить в ней потоки, не зная внутренней структуры.
/// Кто пользуется очередями (все — через [`SchedulerInterface::block_*`]):
///
/// ```text
///   IPC-endpoint   — очередь заблокированных отправителей/получателей
///                    (rendezvous L4: FIFO, wake_one на встрече)
///   DeviceLock     — очередь претендентов на эксклюзивный claim устройства
///   (будущее) мьютексы/futex — тот же контракт
/// ```
///
/// Контракт пары «блокировка -> разбуждение» (строго, иначе потеряются
/// потоки):
///   1. поток, который засыпает, сначала переводится в `Blocked`
///      (`TcbManager::thread_set_state` — хук `deschedule` бекенда),
///      ЗАТЕМ паркуется в очередь (`block_push`);
///   2. разбуждение: подсистема достаёт поток из очереди
///      (`block_pop_front` / `block_remove`) и переводит его в `Ready`
///      (`TcbManager::thread_set_state` — хук `enqueue`);
///   3. бекенд ГАРАНТИРУЕТ, что `block_push`/`block_pop_front`/`block_len`
///      для живой очереди не отказывают по причинам, кроме `Backend(..)`,
///      и что порядок очереди — FIFO (wake_one будит самый старый поток).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord, Default)]
pub struct BlockQueueId(pub u64);

impl BlockQueueId {
    #[inline]
    pub const fn new(bits: u64) -> Self {
        Self(bits)
    }

    #[inline]
    pub const fn as_u64(self) -> u64 {
        self.0
    }
}

/// Пустая очередь — легальный идентификатор только ДО первого push.
pub const BLOCK_QUEUE_NONE: BlockQueueId = BlockQueueId(0);

/// Отказ планировщика-бекенда на уведомлении или команде.
#[derive(Debug, Error, Clone, PartialEq, Eq)]
#[non_exhaustive]
pub enum SchedulerError {
    /// `cpu` вне диапазона, известного бекенду.
    #[error("cpu {0} is not a valid target for the scheduler")]
    InvalidCpu(CpuId),

    /// Задача неизвестна бекенду (например, `deschedule` задачи, которую
    /// бекенд уже снял с учёта).
    #[error("task {0} is unknown to the scheduler")]
    UnknownTask(TaskId),

    /// Любой другой отказ бекенда (переполнение очереди готовых задач,
    /// отказ синхронизации и т.п.).
    #[error("scheduler backend rejected operation: {0}")]
    Backend(&'static str),
}

/// Контракт планировщика-бекенда.
///
/// Реализуется кодом ВНЕ крейта (как [`crate::hal::traits::mmap::MMAPInterface`]
/// и [`crate::hal::traits::kmap::KMAPInterface`]). Все методы принимают
/// `&self`: сериализация внутреннего состояния — забота бекенда (spin-локи
/// и т.п.), менеджер задач не навязывает модель синхронизации.
///
/// Трейт object-safe: бекенд хранится у [`crate::task::TcbManager`] как
/// `&'static dyn SchedulerInterface` — планировщик в ядре глобальный
/// сервис со временем жизни программы.
///
/// Контракт реентерабельности (общий с `TcbManager`): хуки вызываются под
/// `borrow_mut` менеджера задач, поэтому синхронный реентери в методы
/// `TcbManager` из хука — паника заимствования. Бекенд, которому нужно
/// состояние задачи, обязан кэшировать его у себя (см. также
/// `TcbManager::self_slot` — «кэшируется планировщиком»).
pub trait SchedulerInterface {
    /// Задача, исполняющаяся сейчас на `cpu`; `None` — CPU исполняет idle.
    ///
    /// Источник истины о текущей задаче — планировщик, а не `TaskState`:
    /// состояние в TCB обновляется платформенным glue ПОСЛЕ переключения,
    /// поэтому между `switch_context` и `set_state(.., Running)` окно, в
    /// котором верить можно только бекенду.
    fn current(&self, cpu: CpuId) -> Option<TaskId>;

    /// Задача готова к диспетчеризации: создана или вернулась в `Ready`
    /// из `Blocked`/`Suspended`.
    ///
    /// Вызывается `TcbManager` ДО фиксации перехода: отказ бекенда
    /// (`Err`) оставляет автомат состояний нетронутым. Бекенд не имеет
    /// права синхронно диспетчеризовать задачу внутри этого вызова —
    /// диспетчеризация происходит только в [`Self::switch_context`].
    fn enqueue(&self, task: TaskId) -> Result<(), SchedulerError>;

    /// Задача более не исполняема: `Blocked`, `Suspended` или `Dead`.
    ///
    /// Вызывается `TcbManager` ДО фиксации перехода. Вернув `Ok`, бекенд
    /// ГАРАНТИРУЕТ, что задача никогда больше не будет диспетчеризована
    /// (для `Dead` — безусловно; для `Blocked`/`Suspended` — до парного
    /// `enqueue`). Если задача сейчас исполняется на каком-то CPU, бекенд
    /// обязан обеспечить переключение с неё (вытеснение/отложенный
    /// `switch_context` — модель бекенда).
    fn deschedule(&self, task: TaskId) -> Result<(), SchedulerError>;

    /// Приоритет задачи изменён (переоценка очередей — забота бекенда).
    ///
    /// Вызывается ДО применения нового приоритета к TCB: отказ бекенда
    /// откатывает и смену приоритета.
    fn on_priority_change(
        &self,
        task: TaskId,
        priority: TaskPriority,
    ) -> Result<(), SchedulerError>;

    /// Переключение контекста на `cpu`: `prev` уступает процессор (или
    /// `None` — диспетчеризация из idle), `next` диспетчируется.
    ///
    /// # Контракт Meltdown/Spectre (обязателен для реализации)
    ///
    /// 1. Активация адресного пространства `next` — ТОЛЬКО через
    ///    архитектурный бекенд (реализация `MMAPInterface`/`KMAPInterface`
    ///    фасада задачи). Прямые записи в регистры таблиц страниц
    ///    запрещены: изоляция KPTI и права страниц исполняются там,
    ///    и дублировать их здесь — значит разъехаться с KMap.
    /// 2. В момент возврата в пользовательский режим активная
    ///    пользовательская таблица `next` обязана содержать ядро ровно в
    ///    объёме, разрешённом KMap, по которой создавался её фасад: при
    ///    [`IsolationPolicy::UserTableIsolation`] — трамплин входа и
    ///    user-shared страницы и НИЧЕГО больше; полное supervisor-only
    ///    ядро допустимо только при [`IsolationPolicy::MapFullKernel`].
    /// 3. `Self::isolation_policy(cpu)` обязан совпадать с политикой
    ///    `MemoryManager::kmap().policy()` на момент создания фасадов.
    ///    Расхождение — ошибка конфигурации платформы, а не то, что крейт
    ///    может починить за бекендом.
    /// 4. После успешного переключения платформенный glue переводит
    ///    `next` в `Running` через `TcbManager::set_state` (хука на
    ///    `Running` нет: диспетчеризация — событие самого планировщика).
    ///
    /// `Err` означает, что переключение НЕ выполнено: `prev` обязан
    /// остаться исполняющейся задачей (бекенд сам приводит себя в
    /// согласованное состояние до возврата ошибки).
    fn switch_context(
        &self,
        cpu: CpuId,
        prev: Option<TaskId>,
        next: TaskId,
    ) -> Result<(), SchedulerError>;

    /// Политика изоляции, под которую бекенд выполняет переключения на
    /// `cpu` (см. контракт [`Self::switch_context`]).
    ///
    /// Дефолт — консервативная KPTI-изоляция
    /// ([`IsolationPolicy::conservative`]): бекенд, доказавший платформой
    /// отсутствие Meltdown-класса уязвимостей, переопределяет на
    /// [`IsolationPolicy::MapFullKernel`]. Смысл дефолта: забывчивый
    /// бекенд обязан получить самую строгую политику, а не самую дешёвую.
    fn isolation_policy(&self, _cpu: CpuId) -> IsolationPolicy {
        IsolationPolicy::conservative()
    }

    // ==== Очереди блокировки (живут В бекенде планировщика) ====
    //
    // Дефолт-реализации — отказ «не поддержано»: бекенды без блокировок
    // компилируются, но подсистемы, требующие ожидания (IPC-rendezvous,
    // claim устройства), получают детерминированный SchedulerError::Backend.
    // Бекенд с блокировками ОБЯЗАН переопределить все шесть методов и
    // держать FIFO-порядок (контракт BlockQueueId).

    /// Создать новую очередь блокировки. Идентификатор уникален в рамках
    /// бекенда; очередь пуста.
    fn block_queue_create(&self) -> Result<BlockQueueId, SchedulerError> {
        Err(SchedulerError::Backend(
            "block queues are not supported by this scheduler",
        ))
    }

    /// Уничтожить очередь. Обязана быть пустой (контракт вызывающего —
    /// подсистема сначала будит все parked-потоки); бекенд вправе
    /// проверить это и отказать.
    fn block_queue_destroy(&self, _queue: BlockQueueId) -> Result<(), SchedulerError> {
        Err(SchedulerError::Backend(
            "block queues are not supported by this scheduler",
        ))
    }

    /// Припарковать поток в очередь. Поток к этому моменту уже `Blocked`
    /// (контракт BlockQueueId, шаг 1) — бекенд лишь учитывает его в очереди.
    fn block_push(&self, _queue: BlockQueueId, _thread: ThreadId) -> Result<(), SchedulerError> {
        Err(SchedulerError::Backend(
            "block queues are not supported by this scheduler",
        ))
    }

    /// Снять конкретный поток с очереди (точечное разбуждение, например
    /// отмена ожидания). `Ok(true)` — был в очереди и снят.
    fn block_remove(
        &self,
        _queue: BlockQueueId,
        _thread: ThreadId,
    ) -> Result<bool, SchedulerError> {
        Err(SchedulerError::Backend(
            "block queues are not supported by this scheduler",
        ))
    }

    /// Достать самый старый (FIFO) поток очереди — кандидат на разбуждение.
    /// `Ok(None)` — очередь пуста. Само разбуждение (перевод в `Ready`)
    /// выполняет вызывающий через `TcbManager`.
    fn block_pop_front(&self, _queue: BlockQueueId) -> Result<Option<ThreadId>, SchedulerError> {
        Err(SchedulerError::Backend(
            "block queues are not supported by this scheduler",
        ))
    }

    /// Число припаркованных потоков (аудит/тесты).
    fn block_len(&self, _queue: BlockQueueId) -> Result<usize, SchedulerError> {
        Err(SchedulerError::Backend(
            "block queues are not supported by this scheduler",
        ))
    }

    /// Уступить CPU немедленно (L4 yield, сискол THREAD_YIELD): бекенд
    /// перевыпускает планировщик для ТЕКУЩЕГО потока — либо сразу
    /// (вытеснение в точке вызова), либо отложенно (флаг перевыпуска,
    /// обрабатываемый на выходе из сискола).
    ///
    /// Дефолт — no-op (`Ok(())`): кооперативный бекенд без приоритетных
    /// очередей трактует yield как пустой звук, и это корректно —
    /// вызывающий продолжит исполняться. Бекенды с очередями готовности
    /// обязаны переопределить.
    fn yield_now(&self, _current: ThreadId) -> Result<(), SchedulerError> {
        Ok(())
    }

    /// Тик планировщика (источник — платформенный таймер): бекенд ведёт
    /// квант/учёт времени; `&self` (как весь трейт) — внутренняя
    /// мутабельность на совести бекенда (глобальный синглтон).
    fn perform_tick(&self, delta: u64);
}
