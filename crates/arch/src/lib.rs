// ==== ARCH: архитектурные примитивы x86_64 ====
//
// Слой — ТОЛЬКО механика ISA без политики: что делает железо и как до
// него дотянуться. Решения (кого планировать, какие таблицы строить,
// какую политику изоляции применять) живут выше — backend/startup.
//
// Разделение труда с готовым крейтом `x86_64` (принцип проекта: готовые
// крейты по краям): он даёт типы (VirtAddr/PhysAddr), инструкции
// (cli/sti/hlt, invlpg, rdmsr/wrmsr, lgdt/lidt, TSC), таблицы
// (PageTable/mapper, GDT/TSS) и порт I/O. Наше — то, чего у него нет:
//   * `serial`  — драйвер COM1 (16550) под поллингом;
//   * `percpu`  — per-CPU блоки через GS-базу и gs:[off]-доступ;
//   * `boot`    — константы загрузочного/SIPI-протокола нашей связки
//                 «заглушка -> ядро -> AP».
// `pub use x86_64` — бекенду не нужен второй слой косвенности.
#![no_std]

pub mod boot;
pub mod percpu;
pub mod serial;

/// Готовый архитектурный крейт-стандарт: реэкспорт для бекенда.
pub use x86_64;
