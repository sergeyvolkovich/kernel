// ==== CPU / idle-wake contracts ====

/// Статическая топология CPU платформы (максимум поддерживаемых).
pub trait CPUInterface {
    const MAX_CPU_COUNT: usize;
}

/// Idle-wake контракт (v0.20): шов, через который НЕЙТРАЛЬНАЯ политика
/// балансировщика (core/sched_lb) решает «когда и кого» разбудить, а
/// ПЛАТФОРМА знает «как»:
///   * x86_64 (platform/backend) — LAPIC resched-IPI; HLT-парковка
///     считается C1 (класс 1); более глубокие классы придут вместе с
///     mwait-хинтами;
///   * порт на другую ISA реализует тот же контракт (например, SGI на
///     ARM) без единой правки политики.
///
/// Инварианты реализации:
///   * `idle_wake_class` монотонна по цене пробуждения: 0 = ядро
///     исполняется (будить не надо), 1 = мелкая парковка (C1), далее —
///     глубже/дороже;
///   * `kick_cpu` обязан быть безопасным в ЛЮБОМ состоянии цели:
///     бегущему ядру кик — просто запрос перепланирования, спящему —
///     пробуждение в pull-путь балансировщика.
pub trait IdleWakeInterface: Sync {
    /// Класс стоимости пробуждения CPU (см. семантику выше).
    fn idle_wake_class(&self, cpu: usize) -> u8;

    /// Доставить resched-кик CPU (транспорт заархитектурен: IPI/SGI).
    fn kick_cpu(&self, cpu: usize);
}
