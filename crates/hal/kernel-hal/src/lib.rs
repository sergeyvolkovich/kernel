// ==== kernel-hal: контрактный слой HAL (v0.15) ====
//
// Здесь живут ТОЛЬКО контракты платформы (трейты) и универсальные типы
// (PhysAddr, Bdf, DevicePath...). Механизмы ядра (IrqRouter: GSI->endpoint),
// io-фасад и syscall-хендлеры остались в kernel — они зависят от
// capability/ipc/task и сломали бы независимость этого крейта.
//
// Структурная гарантия изоляции (запрос v0.14/v0.15: «экспозиция
// архитектуры не проникает между крейтами»): у крейта НЕТ зависимостей
// на какие-либо крейты workspace — cargo физически не позволит этому
// слою увидеть ни менеджеры ядра, ни платформенные детали бекенда.
// Обратное ребро тоже запрещено: generic-ядро (kernel) зависит только
// на kernel-hal и не видит backend/arch. Единственное место, где живут
// архитектурные детали, — бекенд (x86_64), реализующий эти контракты.

// Тесты и host-утилиты гоняются на std; боевой крейт — no_std.
