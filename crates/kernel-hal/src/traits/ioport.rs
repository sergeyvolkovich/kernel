// ==== Платформенный сервис I/O-портов (медитация доступа юзерспейса) ====
//
// Ядро арх-агностично: инструкция in/out — свойство ISA, его исполняет
// ПЛАТФОРМЕННЫЙ бекенд (x86_64: port I/O), а syscall-хендлер IOP_IN/
// IOP_OUT только проверяет IoResource(IoPort)-capability и делегирует
// сюда. До установки сервиса хендлеры возвращают ENOSYS (порт без
// платформы бессмысленен).
//
// Безопасность: доступ МЕДИТИРОВАНcapability — прямой in/out из
// юзерспейса не существует (IOPL=0 в EFLAGS пользовательских контекстов),
// каждое обращение проходит проверку диапазона портов. Модель близка
// seL4 I/O port caps, но с исполнением в ядре (безопаснее в TCG/QEMU и
// не требует TSS iopl-map).

/// Сервис доступа к I/O-портам платформы (устанавливает бекенд x86_64).
pub trait IoPortOps: Sync + Send {
    /// Чтение ширины `width` байт (1 | 2 | 4) из порта.
    fn port_in(&self, port: u16, width: u8) -> u32;

    /// Запись `value` ширины `width` байт (1 | 2 | 4) в порт.
    fn port_out(&self, port: u16, width: u8, value: u32);
}
